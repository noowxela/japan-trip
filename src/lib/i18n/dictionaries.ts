export const dictionaries: Record<Locale, Record<DictKey, string>> = {
  en: en as Record<DictKey, string>,
  zh,
};

export function t(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const primary = dictionaries[locale]?.[key as DictKey];
  const fallback =
    primary ??
    dictionaries.zh[key as DictKey] ??
    dictionaries.en[key as DictKey] ??
    key;
  if (!vars) return fallback;
  return fallback.replace(/\{(\w+)\}/g, (_, name: string) =>
    vars[name] != null ? String(vars[name]) : `{${name}}`,
  );
}

export function labelType(locale: Locale, value: string | null | undefined) {
  if (!value) return null;
  const key = `type.${value}`;
  const mapped = dictionaries[locale]?.[key as DictKey];
  if (mapped) return mapped;
  if (locale !== "zh") {
    const zhMapped = dictionaries.zh[key as DictKey];
    if (zhMapped) return dictionaries.en[key as DictKey] ?? value;
  }
  return dictionaries.en[key as DictKey] ?? value;
}

